import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { homedir } from 'node:os'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const crate = join(root, 'rust/water-geometry')
const manifestPath = join(crate, 'artifact.json')
const assetModule = join(root, 'src/features/water/lib/waterGeometryAsset.ts')
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex')
const sourceFiles = ['Cargo.toml', 'Cargo.lock', ...readdirSync(join(crate, 'src')).filter(name => name.endsWith('.rs')).sort().map(name => `src/${name}`)]
const sourceHash = () => sha256(Buffer.concat([
  ...sourceFiles.flatMap(name => [Buffer.from(`${name}\0`), readFileSync(join(crate, name))]),
  Buffer.from('scripts/build-water-geometry.mjs\0'), readFileSync(fileURLToPath(import.meta.url)),
]))
const moduleText = url => `// Generated by npm run wasm:build.\nexport const WATER_GEOMETRY_URL = '${url}'\n`

function verify() {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (!/^\/wasm\/water-geometry\.[a-f0-9]{16}\.wasm$/.test(manifest.url)) throw new Error('Invalid geometry asset path')
  const bytes = readFileSync(join(root, 'public', manifest.url))
  if (manifest.sourceSha256 !== sourceHash() || manifest.sha256 !== sha256(bytes)
    || readFileSync(assetModule, 'utf8') !== moduleText(manifest.url)) throw new Error('Rust geometry artifact is stale; run npm run wasm:build')
  if (!WebAssembly.validate(bytes) || WebAssembly.Module.imports(new WebAssembly.Module(bytes)).length !== 0) throw new Error('Invalid standalone geometry module')
  console.log(`Rust geometry verified: ${bytes.length} bytes (${manifest.compiler})`)
}

if (process.argv.includes('--verify')) {
  verify()
} else {
  const cargo = existsSync(join(homedir(), '.cargo/bin/cargo')) ? join(homedir(), '.cargo/bin/cargo') : 'cargo'
  const rustc = existsSync(join(dirname(cargo), 'rustc')) ? join(dirname(cargo), 'rustc') : 'rustc'
  const sysrootResult = spawnSync(rustc, ['--print', 'sysroot'], { encoding: 'utf8' })
  const versionResult = spawnSync(rustc, ['--version', '--verbose'], { encoding: 'utf8' })
  const revision = versionResult.stdout?.match(/^commit-hash: ([a-f0-9]{40})$/m)?.[1]
  if (sysrootResult.status !== 0 || !sysrootResult.stdout.trim()) throw new Error('Rust sysroot lookup failed')
  if (versionResult.status !== 0 || !revision) throw new Error('Rust compiler revision lookup failed')
  // std macros can embed the host toolchain path even when project paths are
  // remapped. Use the same /rustc/<revision> source prefix as precompiled std.
  // Encoded flags preserve paths containing spaces.
  const flags = [`--remap-path-prefix=${root}=.`, `--remap-path-prefix=${sysrootResult.stdout.trim()}/lib/rustlib/src/rust=/rustc/${revision}`]
  const result = spawnSync(cargo, ['build', '--locked', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', join(crate, 'Cargo.toml')], {
    cwd: root, stdio: 'inherit', env: { ...process.env, CARGO_ENCODED_RUSTFLAGS: flags.join('\x1f') },
  })
  if (result.status !== 0) throw new Error('Rust build failed; install the wasm32-unknown-unknown target')
  const bytes = readFileSync(join(crate, 'target/wasm32-unknown-unknown/release/zaridasu_water_geometry.wasm'))
  const hash = sha256(bytes)
  const url = `/wasm/water-geometry.${hash.slice(0, 16)}.wasm`
  const compiler = versionResult.stdout.split('\n')[0].trim()
  const manifest = { url, sha256: hash, sourceSha256: sourceHash(), compiler }
  if (process.argv.includes('--check')) {
    const existing = JSON.parse(readFileSync(manifestPath, 'utf8'))
    writeFileSync(join(crate, 'target/rebuild.json'), JSON.stringify({ expected: existing, rebuilt: manifest, bytes: bytes.length }, null, 2) + '\n')
    if (existing.sha256 !== hash || existing.sourceSha256 !== manifest.sourceSha256) {
      console.error(JSON.stringify({ expected: existing, rebuilt: manifest }, null, 2))
      throw new Error('Rebuilt Rust module differs from the distributed artifact')
    }
  } else {
    mkdirSync(join(root, 'public/wasm'), { recursive: true })
    writeFileSync(join(root, 'public', url), bytes)
    writeFileSync(assetModule, moduleText(url))
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
  }
  verify()
}
