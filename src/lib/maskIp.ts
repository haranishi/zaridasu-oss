/**
 * REQ-245 FR-245-05 / REQ-211（PII 最小化）: 管理画面の通報元 IP 表示用マスク。
 *
 * 管理者一覧では既定でマスク表示し、「表示」トグルで原文を確認できる（保存値は変えない・表示のみ）。
 * 従来は IPv4 の末尾オクテットのみをマスクしており、IPv6 アドレスはフルで露出していた。本関数は
 * IPv6 も対象にし、ネットワーク先頭プレフィックスだけを残してホスト/インタフェース識別子を伏せる。
 */
export function maskIp(ip: string): string {
  // IPv6（':' を含む）: 先頭 3 ハイテット（≒ /48 相当の上位プレフィックス）だけ残し、
  // 個体特定に効く残り（サブネット + インタフェース識別子）を xxxx でマスクする。
  // '::' 圧縮形・IPv4-mapped（::ffff:a.b.c.d）も split でそのまま扱い、末尾に :xxxx を付す
  //   例) 2001:0db8:85a3:0000:0000:8a2e:0370:7334 -> 2001:0db8:85a3:xxxx
  //       2001:db8::1                             -> 2001:db8::xxxx
  if (ip.includes(':')) {
    const prefix = ip.split(':').slice(0, 3).join(':')
    return `${prefix}:xxxx`
  }
  // IPv4: 末尾オクテットをマスク（従来動作を保持）。想定外の形式はそのまま返す。
  //   例) 203.0.113.42 -> 203.0.113.xxx
  return ip.replace(/(\.\d+)$/, '.xxx')
}
